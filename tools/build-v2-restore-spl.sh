#!/usr/bin/env bash
# Build the FEL restore SPL for a board from that board's own eMMC capture
# (U-Boot 0010, CONFIG_H713_SPL_RESTORE_BOOT0).
#
#   tools/build-v2-restore-spl.sh CAPTURE_IMG [DEFCONFIG] [OUT]
#
# DEFCONFIG defaults to hy200_qz713_v2_defconfig (the LPDDR3 projector) and
# OUT to build/out/h713-v2-restore-spl.bin.
#
# Takes the stock boot0 at LBA 16 of CAPTURE_IMG and refuses unless it is an
# eGON.BT0 of exactly 32 KiB with a correct checksum, and its declared DRAM
# type and clock match DEFCONFIG. It writes the boot0 as a C array into the
# build directory's include/ (never the source tree: it is a vendor binary,
# and per board), builds spl/sunxi-spl.bin, and checks the payload is in it.
# The SPL itself refuses to compile on a DRAM-type mismatch too.
#
# Use (writes eMMC LBA 16..79, then halts):
#   sunxi-fel -p spl OUT        # in a fresh FEL session
# UART: "=== H713 SPL RESTORE BOOT0 ===" ... "RESTORED-OK".
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
img=${1:?CAPTURE_IMG}
def=${2:-hy200_qz713_v2_defconfig}
out=${3:-$ROOT/build/out/h713-v2-restore-spl.bin}
O=$ROOT/build/uboot-restore-${def%_defconfig}

say() { printf '[restore-spl] %s\n' "$*"; }
die() { say "FAIL: $*"; exit 1; }

[ -f "$img" ] || die "missing $img"
UBOOT=$("$ROOT/tools/build/build.sh" uboot-tree)
[ -f "$UBOOT/configs/$def" ] || die "no $def in $UBOOT"
grep -q H713_SPL_RESTORE_BOOT0 "$UBOOT/board/sunxi/Kconfig" ||
  die "U-Boot tree lacks 0010 (H713_SPL_RESTORE_BOOT0)"

want_clk=$(sed -n 's/^CONFIG_DRAM_CLK=//p' "$UBOOT/configs/$def")
if grep -q '^CONFIG_SUNXI_DRAM_H713_LPDDR3_STOCK=y\|^CONFIG_SUNXI_DRAM_LPDDR3=y' "$UBOOT/configs/$def"; then
  want_type=7
elif grep -q '^CONFIG_SUNXI_DRAM_H713_DDR3_STOCK=y\|^CONFIG_SUNXI_DRAM_DDR3=y' "$UBOOT/configs/$def"; then
  want_type=3
else
  die "$def names no DRAM type"
fi
[ -n "$want_clk" ] || die "$def has no CONFIG_DRAM_CLK"

mkdir -p "$O/include"
payload="$O/boot0.bin"
dd if="$img" of="$payload" bs=512 skip=16 count=64 status=none

# Verify the boot0 and emit the header.
python3 -I - "$payload" "$O/include/h713_restore_payload.h" "$want_type" "$want_clk" <<'EOF'
import struct, sys, hashlib
src, hdr, want_type, want_clk = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
d = open(src, 'rb').read()
def fail(m): sys.exit(f"[restore-spl] FAIL: {m}")
if len(d) != 32768: fail(f"read {len(d)} bytes, not 32768")
if d[4:12] != b'eGON.BT0': fail(f"magic {d[4:12]!r}, not eGON.BT0")
length = struct.unpack_from('<I', d, 16)[0]
if length != 32768: fail(f"header length {length}, not 32768")
chk = struct.unpack_from('<I', d, 12)[0]
w = list(struct.unpack('<8192I', d)); w[3] = 0x5F0A6C39
if sum(w) & 0xffffffff != chk: fail(f"eGON checksum mismatch (header {chk:#x})")
clk, typ = struct.unpack_from('<II', d, 0x38)
if typ != want_type: fail(f"boot0 DRAM type {typ}, board config wants {want_type}")
if clk != want_clk: fail(f"boot0 DRAM clock {clk}, board config wants {want_clk}")
sha = hashlib.sha256(d).hexdigest()
with open(hdr, 'w') as f:
    f.write(f"/* Generated by tools/build-v2-restore-spl.sh. Do not commit. */\n")
    f.write(f"/* boot0 sha256 {sha}, DRAM type {typ}, clock {clk} MHz */\n")
    f.write(f"#define H713_RESTORE_DRAM_TYPE\t{typ}\n")
    f.write("static const unsigned char h713_restore_payload[32768] = {\n")
    for i in range(0, len(d), 12):
        f.write("\t" + " ".join(f"0x{b:02x}," for b in d[i:i+12]) + "\n")
    f.write("};\n")
print(f"[restore-spl] boot0 ok: eGON.BT0, 32768 B, checksum {chk:#010x}, "
      f"DRAM type {typ}, clock {clk} MHz, sha256 {sha}")
EOF

say "configuring $def + H713_SPL_RESTORE_BOOT0 in $O"
[ -f "$ROOT/build/out/bl31.bin" ] || die "missing build/out/bl31.bin (tools/build/build.sh bl31)"
F=(ARCH=arm HOSTCC=clang CC='clang -target aarch64-linux-gnu'
  LD=ld.lld AR=llvm-ar NM=llvm-nm OBJCOPY=llvm-objcopy OBJDUMP=llvm-objdump
  READELF=llvm-readelf STRIP=llvm-strip KAFLAGS=-fintegrated-as
  KCFLAGS='-fintegrated-as -Wno-error=deprecated-non-prototype -fno-stack-protector'
  BL31="$ROOT/build/out/bl31.bin")
make -C "$UBOOT" O="$O" "${F[@]}" "$def" >/dev/null
"$UBOOT/scripts/config" --file "$O/.config" -e SPL_MMC_WRITE \
  -e H713_SPL_RESTORE_BOOT0 -d H713_SPL_FEL_REENTER --set-val SPL_MAX_SIZE 0x14000
make -C "$UBOOT" O="$O" "${F[@]}" olddefconfig >/dev/null
for opt in SPL_MMC_WRITE H713_SPL_RESTORE_BOOT0; do
  grep -q "^CONFIG_$opt=y" "$O/.config" || die "CONFIG_$opt did not stick"
done
grep -q '^CONFIG_SPL_MAX_SIZE=0x14000' "$O/.config" || die "SPL_MAX_SIZE did not stick"
make -C "$UBOOT" O="$O" "${F[@]}" -j"$(nproc)" spl/sunxi-spl.bin

spl="$O/spl/sunxi-spl.bin"
python3 -I - "$spl" "$payload" <<'EOF' || die "payload not found in the SPL"
import sys
spl, p = open(sys.argv[1], 'rb').read(), open(sys.argv[2], 'rb').read()
sys.exit(0 if p in spl else 1)
EOF
grep -aq 'H713 SPL RESTORE BOOT0' "$spl" || die "restore banner not in the SPL"
mkdir -p "$(dirname "$out")"
install -m 0644 "$spl" "$out"
say "$out: $(stat -c %s "$out") bytes, sha256 $(sha256sum "$out" | cut -c1-64)"
say "boot0 payload embedded; DRAM type and clock match $def"
