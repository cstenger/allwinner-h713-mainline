#!/usr/bin/env python3
"""Build warm-shared.scr: the installed cold HDMI startup, run on a warm boot.

RAM-only test script for the shared cold/warm startup plan
(docs/hdmi-shared-startup-plan-2026-10-23.md). It is the installed
h713-hdmi.scr cold branch, byte for byte, except that:

* it runs only when GP6 holds the cold-path latch value a previous cold
  boot left (48444d49), instead of zero;
* it never writes GP6 (the latch is already set; the itest stays);
* it adds a cold-equivalent census before the logo: GP7 zero, R_CCU PPU
  bus closed, as a cold power-on shows;
* the handoff echo names this path.

The production FIT, bootargs and services are unchanged. Never accesses the
board; nothing is installed.
"""
import argparse,hashlib,importlib.util,json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[2]
HERE=pathlib.Path(__file__).resolve().parent
INSTALLED=ROOT/'build/hdmi-reset-baseline-2026-10-20/artifacts/installed'
SCRIPT_SHA='298fb56d6525e4984d75fd2a0dbe998dd6dba7e813393dd798a4a32371de99fb'
FIT_SHA='0877293b3a71b9ccd28c0f0ef9725752a86dffd243851a5213eb023cd3a51c70'
LATCH='48444d49'
GP6_WRITE='mw.l 0x07090118 0x48444d49 && '
CENSUS='itest.l *0x0709011c == 0 && itest.l *0x070101ac == 0 && '
COLD_ECHO='echo H713 HDMI cold startup handoff verified'
WARM_ECHO='echo H713 WARM-SHARED startup handoff verified'
def sha(p):return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()
def replace_once(s,old,new):
    if s.count(old)!=1:raise ValueError('ambiguous source anchor: '+old[:70])
    return s.replace(old,new)
def stages(text):
    """The setenv stage lines, by name."""
    out={}
    for line in text.splitlines():
        if line.startswith('setenv hdmi_'):
            name,body=line[len('setenv '):].split(' ',1);out[name]=body
    return out
def warm_script(source):
    head,body=source.split('if itest.l *0x07090118 != 0; then\n',1)
    cold=body.split('\nelse\n',1)[1]
    if not cold.endswith('fi\n'):raise ValueError('unexpected script tail')
    cold=cold[:-3]
    head=replace_once(head,'# Generated by tools/hdmi/build-startup.py. Never clear RTC GP6 in software.',
        '# Generated by tools/hdmi/build-warm-shared.py from the installed cold branch. RAM-only warm test; never clear RTC GP6.')
    # hdmi_launch: census first, keep the latch check, drop the latch write.
    head=replace_once(head,"setenv hdmi_launch 'itest.l *0x0306101c == 0 && gpio clear PB5 && "+GP6_WRITE,
        "setenv hdmi_launch 'itest.l *0x0306101c == 0 && "+CENSUS+"gpio clear PB5 && ")
    head=replace_once(head,COLD_ECHO,WARM_ECHO)
    return head+'if itest.l *0x07090118 == '+LATCH+'; then\n'+cold+'else echo H713 WARM-SHARED requires the cold-path latch; false; fi\n'
def build(output):
    if output.exists():raise FileExistsError(output)
    assert sha(INSTALLED/'h713-hdmi.cmd')==SCRIPT_SHA,'installed script changed'
    assert sha(ROOT/'build/out/h713-kernel.fit')==FIT_SHA,'production FIT changed'
    spec=importlib.util.spec_from_file_location('startup',HERE/'build-startup.py');m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
    text=warm_script((INSTALLED/'h713-hdmi.cmd').read_text())
    output.mkdir(parents=True)
    (output/'warm-shared.cmd').write_text(text);(output/'warm-shared.scr').write_bytes(m.legacy_image(text.encode()))
    manifest={'schema':'h713-warm-shared-v1','purpose':'RAM-only warm boot of the installed cold HDMI startup; nothing installed',
      'installed_script_sha256':SCRIPT_SHA,'production_fit_sha256':FIT_SHA,'latch':LATCH,
      'warm_script_sha256':sha(output/'warm-shared.scr'),'warm_cmd_sha256':sha(output/'warm-shared.cmd'),
      'tools':{n:sha(HERE/n) for n in ('build-warm-shared.py','check-warm-shared.py')}|{'run-warm-shared.py':sha(ROOT/'tools/serial/run-warm-shared.py')}}
    (output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(output/'manifest.json')
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter);p.add_argument('--output',required=True,type=pathlib.Path);a=p.parse_args();build(a.output.resolve())
