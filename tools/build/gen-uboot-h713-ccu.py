#!/usr/bin/env python3
"""Generate U-Boot's H713 CCU gate/reset tables from the kernel's CCU driver.

U-Boot and Linux share one device tree, so U-Boot's clock driver must use the
kernel's binding IDs (dt-bindings/{clock,reset}/sun50i-h713-ccu.h). U-Boot only
needs gates and resets; this reads every gate the kernel defines (bus gates and
the enable bit of module clocks) and the kernel's reset map, and writes them as
U-Boot's GATE()/RESET() tables, so the two cannot disagree.

  usage: gen-uboot-h713-ccu.py <kernel ccu-sun50i-h713.c> <output clk_h713.c>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
# Comments sit between macro arguments (/* mux */); drop them before parsing.
text = re.sub(r'/\*.*?\*/', '', open(src).read(), flags=re.S)

# Positional (register, gate) argument indices of the kernel's gate macros.
MACROS = {
    'SUNXI_CCU_GATE': (3, 4),
    'SUNXI_CCU_M_WITH_MUX_GATE': (3, 8),
    'SUNXI_CCU_MP_WITH_MUX_GATE': (3, 10),
    'SUNXI_CCU_MP_WITH_MUX_GATE_POSTDIV': (3, 10),
}


def split_args(s):
    args, depth, cur = [], 0, ''
    for c in s:
        if c == ',' and depth == 0:
            args.append(cur.strip())
            cur = ''
            continue
        depth += c in '({'
        depth -= c in ')}'
        cur += c
    args.append(cur.strip())
    return [' '.join(a.split()) for a in args]


gates = {}
for m in re.finditer(r'^static (SUNXI_CCU_\w+)\((.*?)\);', text, re.M | re.S):
    macro, body = m.group(1), m.group(2)
    if macro not in MACROS:
        continue
    a = split_args(body)
    ri, gi = MACROS[macro]
    gates[a[0]] = (a[ri], a[gi])

# Hand-written structs (dividers etc.) that carry an enable bit.
for m in re.finditer(r'^static struct ccu_\w+ (\w+) = \{(.*?)^\};', text, re.M | re.S):
    name, body = m.group(1), m.group(2)
    en = re.search(r'\.enable\s*=\s*(BIT\(\d+\))', body)
    reg = re.search(r'\.reg\s*=\s*(0x[0-9a-fA-F]+)', body)
    if en and reg and not name.startswith('pll_'):
        gates[name] = (reg.group(1), en.group(1))

hw = re.search(r'sun50i_h713_hw_clks = \{.*?\.hws\s*=\s*\{(.*?)\},', text, re.S).group(1)
# Always-on buses with no enable bit. Consumers (the pin controllers' "apb")
# still enable them; a dummy gate makes that a no-op instead of an
# "unhandled" console line, as U-Boot's D1 table does for its APB0.
BUSES = {'CLK_AHB', 'CLK_APB0', 'CLK_APB1'}

clk_lines = []
for m in re.finditer(r'\[(CLK_\w+)\]\s*=\s*&(\w+)\.common\.hw', hw):
    cid, struct = m.groups()
    if struct in gates:
        reg, bit = gates[struct]
        clk_lines.append(f'\t[{cid}]\t= GATE({reg.lower()}, {bit}),')
    elif cid in BUSES:
        clk_lines.append(f'\t[{cid}]\t= GATE_DUMMY,')

rst = re.search(r'sun50i_h713_ccu_resets\[\] = \{(.*?)\};', text, re.S).group(1)
rst_lines = [f'\t[{r}]\t= RESET({reg.lower()}, {bit}),'
             for r, reg, bit in re.findall(r'\[(RST_\w+)\]\s*=\s*\{\s*(0x[0-9a-fA-F]+),\s*(BIT\(\d+\))\s*\}', rst)]

if not clk_lines or not rst_lines:
    sys.exit('nothing parsed; kernel driver layout changed?')

with open(out, 'w') as f:
    f.write(f'''// SPDX-License-Identifier: GPL-2.0+
/*
 * Allwinner H713 CCU gates and resets, keyed by the kernel's binding IDs.
 *
 * GENERATED by tools/build/gen-uboot-h713-ccu.py (h713 project) from the
 * kernel's drivers/clk/sunxi-ng/ccu-sun50i-h713.c. Regenerate; do not edit.
 */

#include <clk-uclass.h>
#include <dm.h>
#include <errno.h>
#include <clk/sunxi.h>
#include <dt-bindings/clock/sun50i-h713-ccu.h>
#include <dt-bindings/reset/sun50i-h713-ccu.h>
#include <linux/bitops.h>

static struct ccu_clk_gate h713_gates[] = {{
{chr(10).join(clk_lines)}
}};

static struct ccu_reset h713_resets[] = {{
{chr(10).join(rst_lines)}
}};

const struct ccu_desc h713_ccu_desc = {{
	.gates	= h713_gates,
	.resets	= h713_resets,
	.num_gates = ARRAY_SIZE(h713_gates),
	.num_resets = ARRAY_SIZE(h713_resets),
}};
''')
print(f'{len(clk_lines)} gates, {len(rst_lines)} resets -> {out}')
